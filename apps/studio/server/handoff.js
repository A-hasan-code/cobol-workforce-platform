import path from "node:path";
import { transpile } from "@cobol/easylang";
import { tryCobolSource, testSample } from "@cobol/runtime-kit";
import { zipStore } from "./zipStore.js";

function safeName(id) {
  return String(id || "PROGRAM")
    .toUpperCase()
    .replace(/[^A-Z0-9-]/g, "")
    .slice(0, 30) || "PROGRAM";
}

/**
 * Build a downloadable COBOL handoff ZIP for a bank developer.
 */
export function buildHandoffPack(sampleDir, {
  mode = "easy",
  source = "",
  programId = "HANDOFF",
  requireTest = false,
} = {}) {
  const pid = safeName(programId);
  let cobol = "";
  let easySource = "";
  const basedir = path.join(sampleDir, "src");

  if (mode === "easy" || (!source.includes("PROGRAM-ID") && mode !== "cobol")) {
    easySource = String(source || "");
    const t = transpile(easySource, { programId: pid, basedir });
    if (!t.ok) {
      return {
        ok: false,
        stage: "easy",
        diagnostics: t.diagnostics,
        error: "EasyLang transpile failed",
      };
    }
    cobol = t.cobol;
  } else {
    cobol = String(source || "");
    if (!/PROGRAM-ID/i.test(cobol)) {
      return { ok: false, stage: "cobol", error: "COBOL source needs PROGRAM-ID", diagnostics: [] };
    }
  }

  const ran = tryCobolSource(sampleDir, cobol, { programId: pid });
  if (!ran.ok) {
    return {
      ok: false,
      stage: ran.stage || "compile",
      error: ran.stderr || "Compile/run failed",
      diagnostics: ran.diagnostics || [],
      cobol,
    };
  }

  let testResult = null;
  if (requireTest) {
    testResult = testSample(sampleDir);
    if (!testResult.ok) {
      return {
        ok: false,
        stage: "test",
        error: "Sample Test did not PASS — fix before handoff, or download without requireTest",
        diagnostics: [],
        cobol,
        test: testResult,
      };
    }
  }

  const readme = `# COBOL handoff pack

Generated by COBOL Studio (EasyLang → GnuCOBOL).

## Contents
- \`${pid}.cob\` — free-format GnuCOBOL source
${easySource ? `- \`source.easy\` — EasyLang source that produced the COBOL\n` : ""}- \`HOWTO.txt\` — compile locally

## Notes for the receiving developer
1. This was compiled and run with **GnuCOBOL** in the Studio lab.
2. Review SHOW COBOL mapping / business meaning before promoting to IBM/Micro Focus.
3. Not a production bank deploy — lab / sandboxed artifact only.

Program-ID: ${pid}
Generated: ${new Date().toISOString()}
`;

  const howto = `GnuCOBOL (local)
-----------------
cobc -x -free ${pid}.cob -o ${pid}
./${pid}          (or ${pid}.exe on Windows)

Studio lab already proved a successful run before this ZIP was built.
`;

  const files = [
    { name: `${pid}.cob`, content: cobol },
    { name: "README.md", content: readme },
    { name: "HOWTO.txt", content: howto },
  ];
  if (easySource) {
    files.push({ name: "source.easy", content: easySource });
  }

  const zip = zipStore(files);
  return {
    ok: true,
    filename: `${pid}-cobol-handoff.zip`,
    zip,
    cobol,
    stdout: ran.stdout,
    test: testResult,
  };
}
